#!/usr/bin/env python3
"""Rasterizes Natural Earth country polygons into src/worldmap.txt for the menu's world map.

Usage: tools/make-worldmap.py ne_50m_admin_0_countries.geojson > src/worldmap.txt

Source: https://github.com/nvkelso/natural-earth-vector (geojson/ne_50m_admin_0_countries.geojson),
public domain. Only needed when the map should be regenerated, not at build or run time.
"""
import json
import sys

COLS, ROWS = 200, 78          # 1.8 degrees per cell
STEP = 360 / COLS
TOP = 84.0                    # 84N down to 56.4S, Antarctica left out

# Features without a usable ISO code
FALLBACK = {"Somaliland": "SO", "Northern Cyprus": "CY", "Siachen Glacier": "IN"}


def part_code(code, lon, lat):
    """Overseas parts that DB-IP lists as countries of their own."""
    if code == "FR" and lon < -30:
        return "GF" if lat < 10 else "GP"
    if code == "FR" and lon > 40:
        return "RE" if lat < -15 else "YT"
    if code == "NO" and lat > 70:
        return "SJ"
    return code


def inside(x, y, rings):
    hit = False
    for ring in rings:
        j = len(ring) - 1
        for i in range(len(ring)):
            xi, yi = ring[i]
            xj, yj = ring[j]
            if (yi > y) != (yj > y) and x < (xj - xi) * (y - yi) / (yj - yi) + xi:
                hit = not hit
            j = i
    return hit


def main():
    features = json.load(open(sys.argv[1]))["features"]
    parts = []  # (code, bbox, rings)
    labels = {}
    for f in features:
        p = f["properties"]
        code = p["ISO_A2_EH"] if p["ISO_A2_EH"] != "-99" else FALLBACK.get(p["ADMIN"])
        if not code:
            continue
        g = f["geometry"]
        polys = g["coordinates"] if g["type"] == "MultiPolygon" else [g["coordinates"]]
        for rings in polys:
            xs = [pt[0] for pt in rings[0]]
            ys = [pt[1] for pt in rings[0]]
            c = part_code(code, sum(xs) / len(xs), sum(ys) / len(ys))
            parts.append((c, (min(xs), min(ys), max(xs), max(ys)), rings))
        labels.setdefault(code, (p["LABEL_X"], p["LABEL_Y"]))

    grid = [[".."] * COLS for _ in range(ROWS)]
    for r in range(ROWS):
        lat = TOP - (r + 0.5) * STEP
        for c in range(COLS):
            lon = -180 + (c + 0.5) * STEP
            for code, (x0, y0, x1, y1), rings in parts:
                if x0 <= lon <= x1 and y0 <= lat <= y1 and inside(lon, lat, rings):
                    grid[r][c] = code
                    break

    # Countries too small for a cell of their own get the cell under their label
    present = {code for row in grid for code in row}
    for code, (lon, lat) in sorted(labels.items()):
        r, c = int((TOP - lat) / STEP), int((lon + 180) / STEP)
        if code not in present and 0 <= r < ROWS and 0 <= c < COLS:
            grid[r][c] = code

    print(f"# geowarden world map: {COLS}x{ROWS} cells, equirectangular, {STEP} degrees per cell,")
    print(f"# longitude -180..180, latitude {TOP}..{TOP - ROWS * STEP:.1f}. Each cell is an ISO 3166 code, \"..\" = sea.")
    print("# Generated by tools/make-worldmap.py from Natural Earth 1:50m Admin 0 Countries (public domain).")
    for row in grid:
        print("".join(row))


if __name__ == "__main__":
    main()
